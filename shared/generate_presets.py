"""Regenerate the C++ pose table from the shared preview data (no dependencies)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIELDS = (
    "eyeRx", "eyeRy", "eyeY", "leftOpen", "rightOpen", "happyEye", "tilt",
    "mouthY", "mouthW", "mouthCurve", "mouthOpen", "cheek",
)
IDS = ("neutral", "happy", "sad", "angry", "surprised", "blank", "sleepy", "wink")


def generate():
    data = json.loads((ROOT / "shared" / "expressions.json").read_text(encoding="utf-8"))
    expressions = data["expressions"]
    if tuple(item["id"] for item in expressions) != IDS:
        raise ValueError("Expression order must match the C++ Expression enum.")
    lines = ["// Generated by shared/generate_presets.py; edit shared/expressions.json."]
    for key in ("background", "ink", "cheek"):
        rgb = int(data["palette"][key].removeprefix("#"), 16)
        if not 0 <= rgb <= 0xffffff:
            raise ValueError(f"Invalid RGB palette color: {key}")
        lines.append(f"static const std::uint32_t k{key.title()}Rgb = 0x{rgb:06x};")
    lines.append("static const Pose kPresets[ExpressionCount] = {")
    for item in expressions:
        values = ", ".join(f"{float(item['pose'][key]):.6f}f" for key in FIELDS)
        lines.append(f"    {{ {values} }}, // {item['id']}")
    lines.append("};")
    (ROOT / "firmware" / "FacePresets.inc").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    generate()
