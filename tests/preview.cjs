const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'test-results');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1120, height: 960 }, deviceScaleFactor: 1 });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(pathToFileURL(path.join(root, 'preview', 'index.html')).href);
    await page.waitForSelector('[data-expression="wink"]');
    await page.locator('#auto-blink').uncheck();
    const pixels = () => page.locator('#face').evaluate(c => c.toDataURL());
    const faceBefore = await pixels();
    await page.locator('[data-expression="surprised"]').click();
    await page.waitForTimeout(650);
    assert.notEqual(await pixels(), faceBefore, 'Expression changes must change the rendered face.');
    assert.equal(await page.locator('#expression-name').textContent(), '驚き');
    await page.locator('#pause').click();
    const paused = await pixels();
    await page.waitForTimeout(200);
    assert.equal(await pixels(), paused, 'Paused pixels must stay fixed.');
    await page.locator('[data-expression="sad"]').click();
    const selectedWhilePaused = await pixels();
    await page.locator('#pause').click();
    await page.waitForTimeout(80);
    assert.equal(await pixels(), selectedWhilePaused, 'Resuming a selected paused pose must not jump backward.');
    await page.locator('#talk').check();
    const talking1 = await pixels();
    await page.waitForTimeout(140);
    assert.notEqual(await pixels(), talking1, 'Talking must animate the mouth.');
    await page.locator('#talk').uncheck();
    await page.locator('[data-expression="neutral"]').click();
    await page.waitForTimeout(650);
    const eyesOpen = await pixels();
    await page.locator('#blink').click();
    await page.waitForTimeout(75);
    assert.notEqual(await pixels(), eyesOpen, 'Manual blink must close the eyes.');
    await page.waitForTimeout(240);
    assert.equal(await pixels(), eyesOpen, 'Blink must return to the exact starting face.');
    const ids = await page.locator('[data-expression]').evaluateAll(bs => bs.map(b => b.dataset.expression));
    assert.equal(ids.length, 8);
    const distinct = new Set();
    await page.locator('#pause').click();
    for (const id of ids) {
      await page.locator(`[data-expression="${id}"]`).click();
      assert.equal(await page.locator('[aria-pressed="true"][data-expression]').count(), 1);
      distinct.add(await pixels());
    }
    assert.equal(distinct.size, 8, 'All eight poses must be visibly distinct.');
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#save').click();
    const download = await downloadPromise;
    const settingsPath = path.join(output, download.suggestedFilename());
    await download.saveAs(settingsPath);
    const settings = JSON.parse(fs.readFileSync(settingsPath, 'utf8'));
    assert.equal(settings.expression, 'wink');
    assert.equal(settings.pose.rightOpen, 0);
    assert.equal(settings.animation.transitionMs, 450);
    await page.locator('#demo').click();
    const firstDemo = await page.locator('#expression-name').textContent();
    await page.waitForTimeout(2600);
    assert.notEqual(await page.locator('#expression-name').textContent(), firstDemo, 'Demo must advance.');
    await page.locator('#demo').click();
    await page.locator('#pause').click();
    await page.locator('[data-expression="neutral"]').click();
    for (const width of [320, 760, 1120]) {
      await page.setViewportSize({ width, height: 900 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `No horizontal overflow at ${width}px.`);
      assert.ok(await page.evaluate(() => {
        const display = document.querySelector('.display-wrap').getBoundingClientRect();
        const stage = document.querySelector('.stage').getBoundingClientRect();
        return display.left >= stage.left && display.right <= stage.right;
      }), `Round display must fit in its panel at ${width}px.`);
    }
    await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 320, height: 900 });
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.reload();
    await page.waitForSelector('[data-expression="wink"]');
    assert.equal(await page.locator('#pause').textContent(), '再生');
    assert.equal(await page.locator('#auto-blink').isChecked(), false);
    assert.deepEqual(errors, [], 'No browser runtime errors.');
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    await page.setViewportSize({ width: 1120, height: 960 });
    await page.reload();
    await page.waitForSelector('[data-expression="wink"]');
    await page.mouse.move(0, 0);
    fs.mkdirSync(path.join(root, 'artifacts'), { recursive: true });
    await page.screenshot({ path: path.join(root, 'artifacts', 'preview.png'), fullPage: true });
    console.log('PASS: 8 poses, transitions, pause/resume, blink, talking, demo, JSON export, responsive layout, reduced motion.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
