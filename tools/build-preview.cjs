// Generate the file:// compatible browser data from the canonical pose data.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = JSON.parse(fs.readFileSync(path.join(root, 'shared', 'expressions.json'), 'utf8'));
fs.writeFileSync(path.join(root, 'preview', 'presets.js'), '// Generated by tools/build-preview.cjs. Edit shared/expressions.json.\nwindow.FacePresets = ' + JSON.stringify(source, null, 2) + ';\n');
console.log('Generated preview/presets.js');
